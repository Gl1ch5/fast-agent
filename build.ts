#!/usr/bin/env node
// Bundles src/**/*.ts into the single file fa.ts that the installers download.
//   node build.ts           write fa.ts
//   node build.ts --check   fail when fa.ts is out of date (for CI)
// No dependencies: modules are ordered by their imports, local imports are dropped,
// `export` is stripped and node: imports are merged at the top. Top-level names
// must therefore be unique across src/ — the build fails on duplicates.
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const DIR = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.join(DIR, 'src');
const OUT = path.join(DIR, 'fa.ts');
const check = process.argv.includes('--check');

const LOCAL = /^import\s+(?:type\s+)?[\s\S]*?\s+from\s+'(\.{1,2}\/[^']+)';\s*$/;
const NODE = /^import\s+([\s\S]+?)\s+from\s+'(node:[^']+)';\s*$/;

// depth-first from the entry: every module comes after the modules it imports
const order: string[] = [];
const seen = new Set<string>();
function visit(file: string) {
  if (seen.has(file)) return;
  seen.add(file);
  for (const l of fs.readFileSync(file, 'utf8').split('\n')) {
    const m = LOCAL.exec(l);
    if (m && !/^import\s+type\s/.test(l)) visit(path.resolve(path.dirname(file), m[1]));
  }
  order.push(file);
}
visit(path.join(SRC, 'main.ts'));
// type-only modules are never visited above; they hold no code, nothing to add

const defaults = new Map<string, string>();       // node:fs → fs
const named = new Map<string, Set<string>>();     // node:url → {fileURLToPath}
const names = new Map<string, string>();          // top-level name → file
const bodies: string[] = [];
const errors: string[] = [];

for (const file of order) {
  const rel = path.relative(DIR, file).split(path.sep).join('/');
  const out: string[] = [];
  for (const l of fs.readFileSync(file, 'utf8').split('\n')) {
    if (l.startsWith('#!')) continue;
    if (LOCAL.test(l)) continue;
    const nm = NODE.exec(l);
    if (nm) {
      const [, what, spec] = nm;
      const brace = /^\{([^}]*)\}$/.exec(what.trim());
      if (brace) {
        const set = named.get(spec) || new Set<string>();
        for (const n of brace[1].split(',').map((x) => x.trim()).filter(Boolean)) set.add(n);
        named.set(spec, set);
      } else {
        const prev = defaults.get(spec);
        if (prev && prev !== what.trim()) errors.push(`${rel}: ${spec} imported as ${what.trim()}, elsewhere as ${prev}`);
        defaults.set(spec, what.trim());
      }
      continue;
    }
    if (/^import\s/.test(l)) errors.push(`${rel}: unsupported import (keep imports on one line): ${l}`);
    const line = l.replace(/^export\s+(?=(async\s+)?function|const|let|var|class|interface|type\s)/, '');
    const d = /^(?:async\s+)?(?:function\*?|const|let|var|class|interface|type)\s+([A-Za-z_$][\w$]*)/.exec(line);
    if (d) {
      if (names.has(d[1])) errors.push(`duplicate top-level name "${d[1]}" in ${rel} and ${names.get(d[1])}`);
      names.set(d[1], rel);
    }
    out.push(line);
  }
  while (out.length && !out[out.length - 1].trim()) out.pop();
  bodies.push(`// ─── ${rel.replace(/^src\//, '')} ${'─'.repeat(Math.max(3, 74 - rel.length))}\n${out.join('\n').trim()}\n`);
}

if (errors.length) { console.error(errors.map((e) => '✗ ' + e).join('\n')); process.exit(1); }

const imports = [...new Set([...defaults.keys(), ...named.keys()])].sort().map((spec) => {
  const d = defaults.get(spec), n = named.get(spec);
  if (d && n) return `import ${d}, { ${[...n].sort().join(', ')} } from '${spec}';`;
  return d ? `import ${d} from '${spec}';` : `import { ${[...n!].sort().join(', ')} } from '${spec}';`;
});

const result = `#!/usr/bin/env node
// fa — fast agent. One file, zero dependencies. Node >= 22.18 (or Bun).
// Run: node fa.ts            Docs: README.md
// GENERATED by build.ts from src/ — edit the files in src/, then run: node build.ts
${imports.join('\n')}

${bodies.join('\n')}`;

if (check) {
  const curText = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (curText !== result) { console.error('✗ fa.ts is out of date — run: node build.ts'); process.exit(1); }
  console.log('✓ fa.ts is up to date');
  process.exit(0);
}

fs.writeFileSync(OUT, result);
// smoke test: load every module (print mode with an empty prompt stops right before any request)
const tmp = fs.mkdtempSync(path.join(DIR, '.build-'));
const r = spawnSync(process.execPath, [OUT, '-p'], { input: '', encoding: 'utf8', env: { ...process.env, FA_HOME: tmp } });
fs.rmSync(tmp, { recursive: true, force: true });
if (!/no prompt/.test(r.stderr)) { console.error(r.stderr || r.stdout); console.error('✗ fa.ts failed to start'); process.exit(1); }
console.log(`✓ fa.ts · ${order.length} modules · ${result.split('\n').length} lines`);
